import type { ItemDefinition } from '../domain/guide'

function item(
  id: string,
  nameZh: string,
  nameEn: string,
  tier: ItemDefinition['tier'],
  corrupts?: string,
): ItemDefinition {
  return {
    id,
    nameZh,
    nameEn,
    tier,
    icon: `assets/items/${id}.png`,
    ...(corrupts ? { corrupts } : {}),
  }
}

